-- KampusX initial PostgreSQL schema. For NEW, empty databases only.
-- Existing populated databases should be baselined at version 1.
CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL UNIQUE,
 name VARCHAR(255),
 password VARCHAR(255),
 role VARCHAR(255) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE location_types (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE locations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL UNIQUE,
 location_type_id BIGINT NOT NULL REFERENCES location_types(id)
);
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(255) NOT NULL UNIQUE,
 category_head_id BIGINT REFERENCES users(id)
);
CREATE TABLE email_otps (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(255) NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 otp VARCHAR(255) NOT NULL,
 used BOOLEAN NOT NULL,
 purpose VARCHAR(255),
 attempts INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 registration_completed BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 affected_users INTEGER,
 description TEXT NOT NULL,
 priority VARCHAR(255),
 status VARCHAR(255) NOT NULL,
 title VARCHAR(255) NOT NULL,
 reporter_id BIGINT NOT NULL REFERENCES users(id),
 resolver_id BIGINT REFERENCES users(id),
 category_id BIGINT NOT NULL REFERENCES categories(id),
 location_id BIGINT REFERENCES locations(id)
);
CREATE TABLE app_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at TIMESTAMP NOT NULL,
 issue_id BIGINT,
 message VARCHAR(255) NOT NULL,
 is_read BOOLEAN NOT NULL,
 user_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE issue_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment TEXT NOT NULL,
 issue_id BIGINT NOT NULL REFERENCES issues(id),
 user_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE issue_images (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 image_url VARCHAR(255) NOT NULL,
 public_id VARCHAR(255) NOT NULL UNIQUE,
 issue_id BIGINT NOT NULL REFERENCES issues(id)
);
CREATE TABLE issue_votes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id BIGINT NOT NULL REFERENCES issues(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 CONSTRAINT uk_issue_votes_issue_user UNIQUE(issue_id, user_id)
);
